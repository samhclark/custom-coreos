def nft_nat(configs: list[dict]) -> str:
    taps = active_taps(configs)
    tap_input_exclusions = " ".join(
        f'iifname != "{tap_name(cfg)}"' for cfg in taps
    )
    tap_output_exclusions = " ".join(
        f'oifname != "{tap_name(cfg)}"' for cfg in taps
    )
    prerouting = []
    output = []
    for cfg in taps:
        guest = tap_guest(cfg).ip
        for port in cfg["container"].get("ports", []):
            address, host_port = port["host"].rsplit(":", 1)
            protocol = port.get("protocol", "tcp")
            destination = f"{guest}:{port['container']}"
            if address == "0.0.0.0":
                prerouting.append(
                    f"        {tap_input_exclusions} fib daddr type local {protocol} "
                    f"dport {host_port} dnat to {destination}"
                )
                output.append(
                    f"        fib daddr type local {protocol} dport {host_port} "
                    f"dnat to {destination}"
                )
            else:
                prerouting.append(
                    f'        iifname "lo" ip daddr {address} {protocol} '
                    f"dport {host_port} dnat to {destination}"
                )
                output.append(
                    f"        ip daddr {address} {protocol} dport {host_port} "
                    f"dnat to {destination}"
                )
    lines = [
        fleet_header("TAP fleet NAT"),
        "table ip nas_krun_nat {",
        "    chain prerouting {",
        "        type nat hook prerouting priority dstnat; policy accept;",
        *prerouting,
        "    }",
        "",
        "    chain output {",
        "        type nat hook output priority dstnat; policy accept;",
        *output,
        "    }",
        "",
        "    chain postrouting {",
        "        type nat hook postrouting priority srcnat; policy accept;",
    ]
    for cfg in taps:
        if cfg["container"].get("ports"):
            lines.append(
                f'        oifname "{tap_name(cfg)}" ip saddr 127.0.0.0/8 '
                f"ip daddr {tap_guest(cfg).ip} snat to {tap_gateway(cfg).ip}"
            )
    for cfg in taps:
        lines.append(
            f"        ip saddr {tap_guest(cfg).ip} {tap_output_exclusions} masquerade"
        )
    lines += ["    }", "}", ""]
    return "\n".join(lines)


def subid_file(configs: list[dict]) -> str:
    # No header comment: shadow-utils does not document comment support in
    # subuid/subgid, so these files stay bare.
    return "".join(
        f"{cfg['host']['username']}:{cfg['host']['subid-start']}:{SUBID_COUNT}\n"
        for cfg in configs
    )


def write(path: Path, content: str, executable: bool = False) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    changed = not path.exists() or path.read_text() != content
    if changed:
        path.write_text(content)
    if executable:
        path.chmod(0o755)
    print(f"{'wrote' if changed else 'ok   '} {path.relative_to(REPO)}")


def generated_paths(cfg: dict) -> set[Path]:
    uid, slug, name = cfg["host"]["uid"], cfg["_slug"], cfg["service"]["name"]
    paths = {
        OVERLAY / f"usr/lib/sysusers.d/nas-{slug}.conf",
        OVERLAY / f"usr/lib/tmpfiles.d/nas-{slug}-rootless.conf",
        OVERLAY / f"usr/local/bin/ensure-nas-{slug}-account.sh",
        OVERLAY / f"etc/systemd/system/ensure-nas-{slug}-account.service",
    }
    if cfg["container"].get("enabled", True):
        paths.add(OVERLAY / f"etc/containers/systemd/users/{uid}/{name}.container")
    if is_active_tap(cfg):
        paths.add(OVERLAY / f"usr/lib/systemd/network/80-{tap_name(cfg)}.netdev")
        paths.add(OVERLAY / f"usr/lib/systemd/network/80-{tap_name(cfg)}.network")
    return paths


def has_generated_header(path: Path) -> bool:
    if path.is_symlink() or not path.is_file():
        return False
    try:
        with path.open(errors="replace") as generated_file:
            for _ in range(2):
                line = generated_file.readline().rstrip("\n")
                if line.startswith(GENERATED_HEADER_PREFIX) and line.endswith(
                    GENERATED_HEADER_SUFFIX
                ):
                    return True
    except OSError:
        return False
    return False


def remove_stale_generated(expected_paths: set[Path], overlay: Path = OVERLAY) -> None:
    stale_paths = sorted(
        path
        for path in overlay.rglob("*")
        if path not in expected_paths and has_generated_header(path)
    )
    for path in stale_paths:
        path.unlink()
        print(f"removed {path.relative_to(REPO)}")

        # Per-UID Quadlet directories are generator-created. Other output
        # directories are shared with hand-written overlay files.
        users_dir = overlay / "etc/containers/systemd/users"
        if path.parent.parent == users_dir:
            try:
                path.parent.rmdir()
            except OSError:
                pass


def main() -> None:
    toml_paths = sorted(QUADLET_DIR.glob("*.toml"))
    if not toml_paths:
        die(f"no TOML configs found in {QUADLET_DIR}")

    configs = sorted((load_service(p) for p in toml_paths), key=lambda c: c["host"]["uid"])
    validate_fleet(configs)
    verify_sops(configs)

    expected_paths = set()
    fleet_paths = {
        OVERLAY / "etc/nftables/nas-krun-filter.nft",
        OVERLAY / "etc/nftables/nas-krun-nat.nft",
        OVERLAY / "usr/local/bin/nas-krun-network-policy.sh",
        OVERLAY / "etc/systemd/system/nas-krun-network-policy.service",
        OVERLAY / "etc/systemd/system/nftables.service.d/10-nas-krun-policy.conf",
        OVERLAY
        / "etc/systemd/system/systemd-networkd.service.d/10-nas-krun-accounts.conf",
    }
    expected_paths.update(fleet_paths)
    for cfg in configs:
        uid, slug, name = cfg["host"]["uid"], cfg["_slug"], cfg["service"]["name"]
        expected_paths.update(generated_paths(cfg))
        if cfg["container"].get("enabled", True):
            write(
                OVERLAY / f"etc/containers/systemd/users/{uid}/{name}.container",
                container_unit(cfg, configs),
            )
        else:
            print(f"skip  quadlets/{cfg['_toml_path'].name} container (disabled)")
        write(OVERLAY / f"usr/lib/sysusers.d/nas-{slug}.conf", sysusers_conf(cfg))
        write(OVERLAY / f"usr/lib/tmpfiles.d/nas-{slug}-rootless.conf", tmpfiles_conf(cfg))
        write(
            OVERLAY / f"usr/local/bin/ensure-nas-{slug}-account.sh",
            ensure_account_script(cfg),
            executable=True,
        )
        write(
            OVERLAY / f"etc/systemd/system/ensure-nas-{slug}-account.service",
            ensure_account_unit(cfg),
        )
        if is_active_tap(cfg):
            write(
                OVERLAY / f"usr/lib/systemd/network/80-{tap_name(cfg)}.netdev",
                networkd_netdev(cfg),
            )
            write(
                OVERLAY / f"usr/lib/systemd/network/80-{tap_name(cfg)}.network",
                networkd_network(cfg),
            )

    write(OVERLAY / "etc/subuid", subid_file(configs))
    write(OVERLAY / "etc/subgid", subid_file(configs))
    write(
        OVERLAY / "usr/local/bin/nas-krun-network-policy.sh",
        network_policy_script(configs),
        executable=True,
    )
    write(
        OVERLAY / "etc/systemd/system/nas-krun-network-policy.service",
        network_policy_unit(configs),
    )
    write(
        OVERLAY / "etc/systemd/system/nftables.service.d/10-nas-krun-policy.conf",
        nftables_policy_dropin(),
    )
    write(
        OVERLAY
        / "etc/systemd/system/systemd-networkd.service.d/10-nas-krun-accounts.conf",
        networkd_account_ordering(configs),
    )
    write(OVERLAY / "etc/nftables/nas-krun-filter.nft", nft_filter(configs))
    write(OVERLAY / "etc/nftables/nas-krun-nat.nft", nft_nat(configs))
    remove_stale_generated(expected_paths)


if __name__ == "__main__":
    main()
