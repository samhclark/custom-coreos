#!/bin/bash
# ABOUTME: Validates an operator-owned shared ZFS storage layout.
# ABOUTME: This runtime is intentionally validation-only: it never creates,
# ABOUTME: relabels, chowns, or moves production media.

set -euo pipefail

readonly MANIFEST_VERSION="nas-shared-storage-manifest-v1"
readonly REPAIR_REQUIRED_STATUS=78
readonly EXPECTED_LABEL_SUFFIX="object_r:container_file_t:s0"

declare RESOURCE_NAME=""
declare RESOURCE_GROUP=""
declare RESOURCE_GID=""
declare RESOURCE_MODE=""
declare RESOURCE_DATASET=""
declare RESOURCE_PATH=""
declare -a REQUIRED_PATHS=()
declare -A AVAILABLE_POOLS=()
declare -A AVAILABLE_DATASETS=()

die() {
    printf 'nas-prepare-shared-storage: ERROR: %s\n' "$*" >&2
    exit 1
}

repair_required() {
    printf 'nas-prepare-shared-storage: ERROR: %s\n' "$*" >&2
    exit "${REPAIR_REQUIRED_STATUS}"
}

is_absolute_path() {
    local path="$1"

    [[ "${path}" =~ ^/[A-Za-z0-9._/-]+$ ]] &&
        [[ "${path}" != "/" ]] &&
        [[ "${path}" != */ ]] &&
        [[ "${path}" != *//* ]] &&
        [[ "/${path#/}/" != *"/../"* ]] &&
        [[ "/${path#/}/" != *"/./"* ]]
}

is_relative_path() {
    local path="$1"

    [[ "${path}" =~ ^[A-Za-z0-9._-]+(/[A-Za-z0-9._-]+)*$ ]] &&
        [[ "${path}" != "." ]]
}

validate_dataset() {
    [[ "$1" =~ ^[A-Za-z0-9][A-Za-z0-9_.:-]*(/[A-Za-z0-9][A-Za-z0-9_.:-]*)+$ ]]
}

parse_manifest() {
    local manifest="$1"
    local line
    local line_number=0
    local -a fields=()

    while IFS= read -r line || [[ -n "${line}" ]]; do
        ((line_number += 1))
        [[ -n "${line}" ]] || die "line ${line_number}: blank lines are not permitted"
        [[ "${line}" != *[$'\r\t']* ]] || die "line ${line_number}: tabs and carriage returns are not permitted"

        if ((line_number == 1)); then
            [[ "${line}" == "${MANIFEST_VERSION}" ]] || die "line 1: expected ${MANIFEST_VERSION}"
            continue
        fi
        if ((line_number == 2)); then
            [[ "${line}" == "# GENERATED by generate-quadlets.py from quadlets/_fleet.toml — DO NOT EDIT" ]] ||
                die "line 2: expected the generated fleet manifest header"
            continue
        fi

        IFS='|' read -r -a fields <<< "${line}"
        case "${fields[0]}" in
            resource)
                ((${#fields[@]} == 7)) || die "line ${line_number}: resource records require 6 fields"
                [[ -z "${RESOURCE_NAME}" ]] || die "line ${line_number}: duplicate resource record"
                RESOURCE_NAME="${fields[1]}"
                RESOURCE_GROUP="${fields[2]}"
                RESOURCE_GID="${fields[3]}"
                RESOURCE_MODE="${fields[4]}"
                RESOURCE_DATASET="${fields[5]}"
                RESOURCE_PATH="${fields[6]}"
                [[ "${RESOURCE_NAME}" =~ ^[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?$ ]] || die "line ${line_number}: invalid resource name"
                [[ "${RESOURCE_GROUP}" =~ ^[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?$ ]] || die "line ${line_number}: invalid shared group"
                [[ "${RESOURCE_GID}" =~ ^[1-9][0-9]{0,9}$ ]] || die "line ${line_number}: invalid shared group GID"
                ((10#${RESOURCE_GID} <= 4294967295)) || die "line ${line_number}: shared group GID exceeds uint32"
                [[ "${RESOURCE_MODE}" == "2775" ]] || die "line ${line_number}: shared resource mode must be 2775"
                validate_dataset "${RESOURCE_DATASET}" || die "line ${line_number}: invalid dataset"
                is_absolute_path "${RESOURCE_PATH}" || die "line ${line_number}: invalid host path"
                [[ "${RESOURCE_PATH}" == /var/* ]] || die "line ${line_number}: host path must be below /var"
                ;;
            required)
                ((${#fields[@]} == 2)) || die "line ${line_number}: required records require 1 field"
                is_relative_path "${fields[1]}" || die "line ${line_number}: invalid required layout path"
                REQUIRED_PATHS+=("${fields[1]}")
                ;;
            *)
                die "line ${line_number}: unknown record type '${fields[0]}'"
                ;;
        esac
    done < "${manifest}"

    [[ -n "${RESOURCE_NAME}" ]] || die "manifest has no resource record"
    ((${#REQUIRED_PATHS[@]} > 0)) || die "manifest has no required layout paths"
}

require_commands() {
    local command_name

    for command_name in findmnt install matchpathcon stat zfs zpool; do
        command -v "${command_name}" >/dev/null || die "required command '${command_name}' is unavailable"
    done
}

load_zfs_inventory() {
    local output
    local name

    output="$(zpool list -H -o name)" || die "unable to inventory ZFS pools"
    while IFS= read -r name; do
        [[ -n "${name}" ]] && AVAILABLE_POOLS["${name}"]=1
    done <<< "${output}"

    output="$(zfs list -H -o name)" || die "unable to inventory ZFS datasets"
    while IFS= read -r name; do
        [[ -n "${name}" ]] && AVAILABLE_DATASETS["${name}"]=1
    done <<< "${output}"
}

stat_value() {
    stat -c "$1" -- "$2"
}

label_is_ready() {
    local label="$1"

    [[ "${label}" == *:"${EXPECTED_LABEL_SUFFIX}" ]] &&
        [[ "${label}" != *:"${EXPECTED_LABEL_SUFFIX}":* ]]
}

validate_path() {
    local path="$1"
    local source
    local expected

    [[ -d "${path}" && ! -L "${path}" ]] || die "required layout path ${path} is not a real directory"
    source="$(findmnt -rn -o SOURCE -T "${path}")" || die "${path} is not mounted"
    [[ "${source}" == "${RESOURCE_DATASET}" ]] || die "${path} is mounted from '${source}', expected '${RESOURCE_DATASET}'"
    label_is_ready "$(stat_value '%C' "${path}")" ||
        repair_required "${path} has an unexpected SELinux label; operator migration/repair is required"
    expected="$(matchpathcon -n "${path}")" || die "unable to read SELinux policy for ${path}"
    label_is_ready "${expected}" || die "SELinux policy does not assign container_file_t:s0 to ${path}"
    [[ "$(stat_value '%u:%g' "${path}")" == "0:${RESOURCE_GID}" ]] ||
        repair_required "${path} must be owned by root:${RESOURCE_GROUP} (${RESOURCE_GID}); operator migration/repair is required"
    [[ "$(stat_value '%a' "${path}")" == "${RESOURCE_MODE#0}" ]] ||
        repair_required "${path} must have mode ${RESOURCE_MODE}; operator migration/repair is required"
}

(( $# == 1 )) || die "usage: $0 /absolute/path/to/resource.storage-manifest"
MANIFEST="$1"
is_absolute_path "${MANIFEST}" || die "manifest path must be an absolute normalized path"
[[ "${MANIFEST}" == *.storage-manifest && -f "${MANIFEST}" && ! -L "${MANIFEST}" ]] ||
    die "manifest must be a regular, non-symlink .storage-manifest file"

parse_manifest "${MANIFEST}"

RUNTIME_ROOT="/run/nas-storage"
if [[ -n "${NAS_STORAGE_RUNTIME_ROOT:-}" ]]; then
    ((EUID != 0)) || die "NAS_STORAGE_RUNTIME_ROOT is only available to non-root test runs"
    is_absolute_path "${NAS_STORAGE_RUNTIME_ROOT}" || die "invalid test runtime root"
    RUNTIME_ROOT="${NAS_STORAGE_RUNTIME_ROOT}"
fi
READY_DIR="${RUNTIME_ROOT}/${RESOURCE_NAME}"
READY_FILE="${READY_DIR}/ready"
rm -f -- "${READY_FILE}"

require_commands
load_zfs_inventory
pool="${RESOURCE_DATASET%%/*}"
[[ -n "${AVAILABLE_POOLS[${pool}]+x}" ]] || die "required pool '${pool}' does not exist"
[[ -n "${AVAILABLE_DATASETS[${RESOURCE_DATASET}]+x}" ]] || die "required existing dataset '${RESOURCE_DATASET}' does not exist"
validate_path "${RESOURCE_PATH}"
for relative_path in "${REQUIRED_PATHS[@]}"; do
    validate_path "${RESOURCE_PATH}/${relative_path}"
done

install -d -m 0755 -o root -g root "${READY_DIR}"
ready_temporary="${READY_FILE}.$$"
umask 0022
read -r boot_id < /proc/sys/kernel/random/boot_id || die "unable to read the current boot ID"
printf '%s\n' "${boot_id}" > "${ready_temporary}"
mv -f -- "${ready_temporary}" "${READY_FILE}"
printf 'nas-prepare-shared-storage: %s storage is ready\n' "${RESOURCE_NAME}"
